// Association:
//
//	storage.Store -> Ent driver -> generated Ent client -> ontology hooks
//	ontology hooks -> WorkLensWindow -> typed lens result rows
//
// Store owns the bridge between SQLite and Ent so graph writes always pass
// through the generated client with ontology hooks registered.
package entstore

import (
	"context"
	"fmt"
	"time"

	genent "cubicle/services/ontology-service/ent"
	_ "cubicle/services/ontology-service/ent/runtime"
	"cubicle/services/ontology-service/internal/ontologyhooks"
	"cubicle/services/ontology-service/internal/storage"

	"entgo.io/ent/dialect"
	entsql "entgo.io/ent/dialect/sql"
)

// Config controls the generated Ent graph store.
type Config struct {
	DatabasePath string        // DatabasePath is the SQLite file path used for Ent-backed ontology storage.
	BusyTimeout  time.Duration // BusyTimeout is SQLite's local lock wait timeout before write contention fails.
}

// Store owns the SQLite handle and generated Ent client for ontology graph writes.
type Store struct {
	baseStore *storage.Store // baseStore owns SQLite pragmas and the underlying database/sql handle.
	client    *genent.Client // client is the generated Ent DAO/query surface used by service code.
}

// Open creates the Ent-backed graph store, installs ontology hooks, and migrates schema.
func Open(ctx context.Context, cfg Config) (*Store, error) {
	baseStore, err := storage.Open(ctx, storage.Config{
		DatabasePath: cfg.DatabasePath,
		BusyTimeout:  cfg.BusyTimeout,
	})
	if err != nil {
		return nil, err
	}

	driver := entsql.OpenDB(dialect.SQLite, baseStore.DB()) // driver adapts the configured SQLite handle for Ent.
	client := genent.NewClient(genent.Driver(driver))       // client is generated by Ent and owns all ORM builders.
	ontologyhooks.Register(client)
	if err := client.Schema.Create(ctx); err != nil {
		_ = client.Close()
		return nil, fmt.Errorf("migrate ent schema: %w", err)
	}

	return &Store{
		baseStore: baseStore,
		client:    client,
	}, nil
}

// Client returns the generated Ent client.
func (s *Store) Client() *genent.Client {
	if s == nil {
		return nil
	}
	return s.client
}

// Close releases the underlying SQLite handle through Ent's driver.
func (s *Store) Close() error {
	if s == nil {
		return nil
	}
	if s.client != nil {
		return s.client.Close()
	}
	if s.baseStore != nil {
		return s.baseStore.Close()
	}
	return nil
}
