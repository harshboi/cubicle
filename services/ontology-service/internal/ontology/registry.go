package ontology

import "cubicle/services/ontology-service/internal/domain"

const (
	// ObjectWorkstream is a project, initiative, or body of work Cubicle can
	// summarize as a connected operating context.
	ObjectWorkstream domain.ObjectType = "workstream"

	// ObjectTicket is an issue-tracker item such as a Jira ticket. It usually
	// carries source status and connects workstreams to implementation activity.
	ObjectTicket domain.ObjectType = "ticket"

	// ObjectPullRequest is a code-review or change request, typically from
	// GitHub. It connects tickets to concrete code movement.
	ObjectPullRequest domain.ObjectType = "pull_request"

	// ObjectCodeFile is a repository file touched by a pull request or mentioned
	// in evidence. It lets Cubicle answer "what code is involved?".
	ObjectCodeFile domain.ObjectType = "code_file"

	// ObjectDocument is a durable document, spec, or markdown page that can
	// support workstream understanding.
	ObjectDocument domain.ObjectType = "document"

	// ObjectDocumentFragment is a meaningful section or extracted mention within
	// a document. It keeps document-level search from becoming too coarse.
	ObjectDocumentFragment domain.ObjectType = "document_fragment"

	// ObjectMessage is a Slack, mailing-list, chat, or other communication item
	// that can explain why work moved or stalled.
	ObjectMessage domain.ObjectType = "message"

	// ObjectDecision is a recorded choice that affects a workstream. It is not
	// used by the first fixture, but the term reserves the product concept.
	ObjectDecision domain.ObjectType = "decision"

	// ObjectBlocker is something preventing progress, such as missing review,
	// unresolved dependency, or unclear ownership.
	ObjectBlocker domain.ObjectType = "blocker"

	// ObjectRisk is a possible future failure mode. It is separate from Blocker
	// because risks may not be active blockers yet.
	ObjectRisk domain.ObjectType = "risk"

	// ObjectPerson is a user, contributor, assignee, reviewer, or author in the
	// workplace graph.
	ObjectPerson domain.ObjectType = "person"

	// ObjectTeam is a group of people used for ownership, routing, or access
	// reasoning.
	ObjectTeam domain.ObjectType = "team"

	// ObjectActionCandidate is a suggested next step generated by rules or later
	// LLM workflows. It should link back to evidence explaining the suggestion.
	ObjectActionCandidate domain.ObjectType = "action_candidate"
)

const (
	// AssocContains is a containment relationship, such as a workstream
	// containing a ticket or a document containing a fragment.
	AssocContains domain.AssociationType = "contains"

	// AssocHasComponent connects a larger operational object to a meaningful
	// subcomponent without implying strict ownership.
	AssocHasComponent domain.AssociationType = "has_component"

	// AssocImplementedBy connects a ticket, requirement, or work item to a pull
	// request or other implementation artifact.
	AssocImplementedBy domain.AssociationType = "implemented_by"

	// AssocChangesFile connects a pull request or change object to a code file
	// it modifies.
	AssocChangesFile domain.AssociationType = "changes_file"

	// AssocDiscussedIn connects a work item to a message or thread where people
	// discussed it.
	AssocDiscussedIn domain.AssociationType = "discussed_in"

	// AssocDocuments connects an object to the document or note that explains it.
	AssocDocuments domain.AssociationType = "documented_by"

	// AssocSupports connects evidence-like objects to the claim or object they
	// strengthen.
	AssocSupports domain.AssociationType = "supports"

	// AssocBlockedBy connects work to the active blocker preventing progress.
	AssocBlockedBy domain.AssociationType = "blocked_by"

	// AssocOwnedBy connects work, risks, or systems to people or teams
	// responsible for them.
	AssocOwnedBy domain.AssociationType = "owned_by"

	// AssocNeedsAction connects a work item or blocker to a suggested follow-up.
	AssocNeedsAction domain.AssociationType = "needs_action"

	// AssocEvidencedBy connects a claim-like object to explicit supporting
	// evidence when evidence is modeled as a first-class graph object.
	AssocEvidencedBy domain.AssociationType = "evidenced_by"
)

// ObjectTypeDef describes one built-in object type for docs, validation, and
// future GraphQL introspection endpoints.
type ObjectTypeDef struct {
	// Type is the stable machine-readable object type used in graph DTOs.
	Type domain.ObjectType `json:"type"`

	// DisplayName is the short human-readable label shown in tools or docs.
	DisplayName string `json:"display_name"`

	// Description is optional longer documentation for the ontology term.
	Description string `json:"description,omitempty"`
}

// AssociationTypeDef describes one built-in association type for docs,
// validation, and future query planning.
type AssociationTypeDef struct {
	// Type is the stable machine-readable association type used in graph DTOs.
	Type domain.AssociationType `json:"type"`

	// DisplayName is the short human-readable label shown in tools or docs.
	DisplayName string `json:"display_name"`

	// Description is optional longer documentation for the association term.
	Description string `json:"description,omitempty"`

	// Inverse names the reverse association type when Cubicle later chooses to
	// materialize or document inverse semantics.
	Inverse domain.AssociationType `json:"inverse,omitempty"`
}

// Registry is the in-process catalog of built-in ontology terms.
//
// Domain DTOs intentionally remain open, while this registry records the terms
// Cubicle product queries know how to classify today.
type Registry struct {
	// ObjectTypes maps object type strings to their documentation records.
	ObjectTypes map[domain.ObjectType]ObjectTypeDef

	// AssociationTypes maps association type strings to their documentation
	// records.
	AssociationTypes map[domain.AssociationType]AssociationTypeDef
}

// BuiltinRegistry returns Cubicle's built-in object and association vocabulary.
func BuiltinRegistry() Registry {
	// objects is the ordered list of built-in object terms. It is converted to a
	// map below so lookup is cheap for validators and query classifiers.
	objects := []ObjectTypeDef{
		{Type: ObjectWorkstream, DisplayName: "Workstream"},
		{Type: ObjectTicket, DisplayName: "Ticket"},
		{Type: ObjectPullRequest, DisplayName: "Pull request"},
		{Type: ObjectCodeFile, DisplayName: "Code file"},
		{Type: ObjectDocument, DisplayName: "Document"},
		{Type: ObjectDocumentFragment, DisplayName: "Document fragment"},
		{Type: ObjectMessage, DisplayName: "Message"},
		{Type: ObjectDecision, DisplayName: "Decision"},
		{Type: ObjectBlocker, DisplayName: "Blocker"},
		{Type: ObjectRisk, DisplayName: "Risk"},
		{Type: ObjectPerson, DisplayName: "Person"},
		{Type: ObjectTeam, DisplayName: "Team"},
		{Type: ObjectActionCandidate, DisplayName: "Action candidate"},
	}

	// associations is the ordered list of built-in relationship terms. Like
	// objects, it stays source-neutral and product-oriented.
	associations := []AssociationTypeDef{
		{Type: AssocContains, DisplayName: "Contains"},
		{Type: AssocHasComponent, DisplayName: "Has component"},
		{Type: AssocImplementedBy, DisplayName: "Implemented by"},
		{Type: AssocChangesFile, DisplayName: "Changes file"},
		{Type: AssocDiscussedIn, DisplayName: "Discussed in"},
		{Type: AssocDocuments, DisplayName: "Documented by"},
		{Type: AssocSupports, DisplayName: "Supports"},
		{Type: AssocBlockedBy, DisplayName: "Blocked by"},
		{Type: AssocOwnedBy, DisplayName: "Owned by"},
		{Type: AssocNeedsAction, DisplayName: "Needs action"},
		{Type: AssocEvidencedBy, DisplayName: "Evidenced by"},
	}

	// registry is the lookup structure returned to callers. The maps make it
	// obvious that custom terms can exist even when they are not built-ins.
	registry := Registry{
		ObjectTypes:      make(map[domain.ObjectType]ObjectTypeDef, len(objects)),
		AssociationTypes: make(map[domain.AssociationType]AssociationTypeDef, len(associations)),
	}

	// object is each object term being indexed by machine-readable type.
	for _, object := range objects {
		registry.ObjectTypes[object.Type] = object
	}

	// association is each relationship term being indexed by machine-readable
	// type.
	for _, association := range associations {
		registry.AssociationTypes[association.Type] = association
	}
	return registry
}

// HasObjectType reports whether objectType is one of Cubicle's built-ins.
//
// Returning false does not make an object invalid; it means the type is custom
// or not yet known to product query code.
func (r Registry) HasObjectType(objectType domain.ObjectType) bool {
	_, ok := r.ObjectTypes[objectType]
	return ok
}

// HasAssociationType reports whether associationType is one of Cubicle's
// built-ins.
//
// Returning false does not make an association invalid; it means the type is
// custom or not yet known to product query code.
func (r Registry) HasAssociationType(associationType domain.AssociationType) bool {
	_, ok := r.AssociationTypes[associationType]
	return ok
}
